/**
 * @param {SurfaceInventory} inventory
 * @param {string} ownerSymbol
 * @param {string} memberName
 */
export function getInheritedMemberUnits(inventory, ownerSymbol, memberName) {
    const visited = new Set([ownerSymbol]);
    const pending = getDeclarationUnits(inventory, ownerSymbol).flatMap(unit => unit.heritageSymbols ?? []);
    const inheritedUnits = [];

    for (const symbol of pending) {
        if (visited.has(symbol)) {
            continue;
        }

        visited.add(symbol);
        const memberUnits = getPreferredMemberUnits(inventory, symbol, memberName);

        if (memberUnits.length) {
            inheritedUnits.push(...memberUnits);
        }
        else {
            pending.push(...getDeclarationUnits(inventory, symbol).flatMap(unit => unit.heritageSymbols ?? []));
        }
    }

    return inheritedUnits;
}

