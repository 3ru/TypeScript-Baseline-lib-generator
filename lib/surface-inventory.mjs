/**
 * @param {string} fileName
 */
function isBuiltinSourceLibFileName(fileName) {
    if (!fileName.endsWith(".d.ts")) {
        return false;
    }

    if (!fileName.startsWith("lib.")) {
        return false;
    }

    const libName = fileName.slice("lib.".length, -".d.ts".length);

    if (libName === "baseline") {
        return false;
    }

    if (libName.endsWith(".full")) {
        return false;
    }

    if (libName === "esnext.disposable") {
        return false;
    }

    if (libName === "es6") {
        return false;
    }

    if (libName.startsWith("dom") || libName.startsWith("webworker") || libName === "scripthost") {
        return false;
    }

    if (libName === "decorators" || libName === "decorators.legacy") {
        return false;
    }

    return libName === "es5"
        || /^es\d{4}(?:\..+)?$/u.test(libName)
        || /^esnext(?:\..+)?$/u.test(libName);
}

/**
 * @param {string} libFileName
 */
function getLibStageRank(libFileName) {
    const libName = libFileName.replace(/^lib\./u, "").replace(/\.d\.ts$/u, "");

    if (libName === "es5") {
        return 5;
    }

    if (libName.startsWith("esnext")) {
        return Number.POSITIVE_INFINITY;
    }

    const match = /^es(\d{4})(?:\.|$)/u.exec(libName);

    if (match) {
        return Number.parseInt(match[1], 10);
    }

    return Number.POSITIVE_INFINITY;
}

/**
 * @param {string} filePath
 */
async function hashFile(filePath) {
    return `sha256-${createHash("sha256").update(await readFile(filePath)).digest("hex")}`;
}

/**
 * @param {{
 *   units: Array<InventoryUnitRecord & { node: ts.Node; sourceFile: ts.SourceFile; }>;
 *   containers: InventoryContainerRecord[];
 *   fileRecord: InventoryFileRecord;
 *   sourceFile: ts.SourceFile;
 *   statement: ts.Statement;
 *   containerPath: string[];
 *   parentContainerId: string | undefined;
 *   nextOrder: () => number;
 * }} options
 */
function collectStatementUnits(options) {
    const {
        units,
        containers,
        fileRecord,
        sourceFile,
        statement,
        containerPath,
        parentContainerId,
        nextOrder,
    } = options;

    if (ts.isModuleDeclaration(statement) && ts.isIdentifier(statement.name) && statement.body && ts.isModuleBlock(statement.body)) {
        const symbolName = formatSymbolName(containerPath, statement.name.text);

        const container = createContainerRecord({
            fileRecord,
            sourceFile,
            node: statement,
            bodyStart: statement.body.statements.pos,
            bodyEnd: statement.body.statements.end,
            containerKind: "namespace",
            symbolName,
            parentContainerId,
            nextOrder,
        });

        containers.push(container);
        fileRecord.containerIds.push(container.id);

        units.push(createDeclarationUnit({
            fileRecord,
            sourceFile,
            node: statement,
            containerPath,
            parentContainerId,
            nextOrder,
            symbolName,
            declarationKind: "namespace",
            typeRefName: undefined,
            containerId: container.id,
        }));

        for (const childStatement of statement.body.statements) {
            collectStatementUnits({
                units,
                containers,
                fileRecord,
                sourceFile,
                statement: childStatement,
                containerPath: [...containerPath, statement.name.text],
                parentContainerId: container.id,
                nextOrder,
            });
        }

        return;
    }

    if (ts.isInterfaceDeclaration(statement) && ts.isIdentifier(statement.name)) {
        const symbolName = formatSymbolName(containerPath, statement.name.text);

        const container = createContainerRecord({
            fileRecord,
            sourceFile,
            node: statement,
            bodyStart: statement.members.pos,
            bodyEnd: statement.members.end,
            containerKind: "interface",
            symbolName,
            parentContainerId,
            nextOrder,
        });

        containers.push(container);
        fileRecord.containerIds.push(container.id);

        units.push(createDeclarationUnit({
            fileRecord,
            sourceFile,
            node: statement,
            containerPath,
            parentContainerId,
            nextOrder,
            symbolName,
            declarationKind: "interface",
            typeRefName: undefined,
            containerId: container.id,
        }));

        for (const member of statement.members) {
            const memberUnit = createMemberUnit({
                fileRecord,
                sourceFile,
                node: member,
                ownerSymbol: symbolName,
                containerPath: [...containerPath, statement.name.text],
                parentContainerId: container.id,
                nextOrder,
            });

            if (memberUnit) {
                units.push(memberUnit);
            }
        }

        return;
    }

    if (ts.isClassDeclaration(statement) && statement.name && ts.isIdentifier(statement.name)) {
        const symbolName = formatSymbolName(containerPath, statement.name.text);

        const container = createContainerRecord({
            fileRecord,
            sourceFile,
            node: statement,
            bodyStart: statement.members.pos,
            bodyEnd: statement.members.end,
            containerKind: "class",
            symbolName,
            parentContainerId,
            nextOrder,
        });

        containers.push(container);
        fileRecord.containerIds.push(container.id);

        units.push(createDeclarationUnit({
            fileRecord,
            sourceFile,
            node: statement,
            containerPath,
            parentContainerId,
            nextOrder,
            symbolName,
            declarationKind: "class",
            typeRefName: undefined,
            containerId: container.id,
        }));

        for (const member of statement.members) {
            const memberUnit = createMemberUnit({
                fileRecord,
                sourceFile,
                node: member,
                ownerSymbol: symbolName,
                containerPath: [...containerPath, statement.name.text],
                parentContainerId: container.id,
                nextOrder,
            });

            if (memberUnit) {
                units.push(memberUnit);
            }
        }

        return;
    }

    if (ts.isVariableStatement(statement)) {
        if (statement.declarationList.declarations.length !== 1) {
            throw new Error(
                `${fileRecord.libFileName} contains a variable statement with multiple declarators. `
                    + "Each runtime global must have its own inventory unit.",
            );
        }

        const declaration = statement.declarationList.declarations[0];

        if (declaration?.type && ts.isTypeLiteralNode(declaration.type) && ts.isIdentifier(declaration.name)) {
            const symbolName = formatSymbolName(containerPath, declaration.name.text);

            const container = createContainerRecord({
                fileRecord,
                sourceFile,
                node: statement,
                bodyStart: declaration.type.members.pos,
                bodyEnd: declaration.type.members.end,
                containerKind: "type-literal-var",
                symbolName,
                parentContainerId,
                nextOrder,
            });

            containers.push(container);
            fileRecord.containerIds.push(container.id);

            units.push(createDeclarationUnit({
                fileRecord,
                sourceFile,
                node: statement,
                containerPath,
                parentContainerId,
                nextOrder,
                symbolName,
                declarationKind: "var",
                typeRefName: symbolName,
                containerId: container.id,
            }));

            for (const member of declaration.type.members) {
                const memberUnit = createMemberUnit({
                    fileRecord,
                    sourceFile,
                    node: member,
                    ownerSymbol: symbolName,
                    containerPath: [...containerPath, declaration.name.text],
                    parentContainerId: container.id,
                    nextOrder,
                });

                if (memberUnit) {
                    units.push(memberUnit);
                }
            }

            return;
        }
    }

    units.push(createDeclarationUnit({
        fileRecord,
        sourceFile,
        node: statement,
        containerPath,
        parentContainerId,
        nextOrder,
        symbolName: getStatementSymbolName(statement, containerPath),
        declarationKind: getDeclarationKind(statement),
        typeRefName: getTypeReferenceName(statement),
        containerId: undefined,
    }));
}

/**
 * @param {{
 *   fileRecord: InventoryFileRecord;
 *   sourceFile: ts.SourceFile;
 *   node: ts.Node;
 *   bodyStart: number;
 *   bodyEnd: number;
 *   containerKind: "namespace" | "interface" | "class" | "type-literal-var";
 *   symbolName: string;
 *   parentContainerId: string | undefined;
 *   nextOrder: () => number;
 * }} options
 * @returns {InventoryContainerRecord & { node: ts.Node; sourceFile: ts.SourceFile; bodyStart: number; bodyEnd: number; }}
 */
function createContainerRecord(options) {
    const {
        fileRecord,
        sourceFile,
        node,
        bodyStart,
        bodyEnd,
        containerKind,
        symbolName,
        parentContainerId,
        nextOrder,
    } = options;

    return {
        id: `${fileRecord.libFileName}::container::${containerKind}::${symbolName}::${nextOrder()}`,
        libFileName: fileRecord.libFileName,
        containerKind,
        symbolName,
        parentContainerId,
        headerText: stripSourceFilePreamble(getNodeSlice(fileRecord.sourceText, node.getFullStart(), bodyStart)).replace(/^(?:\r?\n)+/, "").trimEnd(),
        footerText: getNodeSlice(fileRecord.sourceText, bodyEnd, node.end).trimStart(),
        order: fileRecord.unitIds.length + fileRecord.containerIds.length,
        bodyStart,
        bodyEnd,
        node,
        sourceFile,
    };
}

/**
 * @param {{
 *   fileRecord: InventoryFileRecord;
 *   sourceFile: ts.SourceFile;
 *   node: ts.Node;
 *   containerPath: string[];
 *   parentContainerId: string | undefined;
 *   nextOrder: () => number;
 *   symbolName: string | undefined;
 *   declarationKind: DeclarationKind;
 *   typeRefName: string | undefined;
 *   containerId: string | undefined;
 * }} options
 * @returns {InventoryUnitRecord & { node: ts.Node; sourceFile: ts.SourceFile; }}
 */
function createDeclarationUnit(options) {
    const {
        fileRecord,
        sourceFile,
        node,
        containerPath,
        parentContainerId,
        nextOrder,
        symbolName,
        declarationKind,
        typeRefName,
        containerId,
    } = options;

    /** @type {InventoryUnitRecord & { node: ts.Node; sourceFile: ts.SourceFile; }} */
    const unit = {
        id: createUnitId(fileRecord.libFileName, symbolName ?? "anonymous", nextOrder()),
        libFileName: fileRecord.libFileName,
        unitKind: "declaration",
        declarationKind,
        containerPath,
        parentContainerId,
        containerId,
        symbolName,
        ownerSymbol: undefined,
        memberName: undefined,
        typeRefName,
        declaredSymbols: symbolName ? [symbolName] : [],
        dependencySymbols: [],
        dependencyUnitIds: [],
        order: fileRecord.unitIds.length,
        text: getNodeText(fileRecord.sourceText, node),
        parameterNames: getParameterNames(node),
        surfacePath: symbolName,
        node,
        sourceFile,
    };

    if (ts.isModuleDeclaration(node) && (node.flags & ts.NodeFlags.GlobalAugmentation) !== 0) {
        unit.isGlobalAugmentation = true;
    }

    fileRecord.unitIds.push(unit.id);

    return unit;
}

/**
 * @param {{
 *   fileRecord: InventoryFileRecord;
 *   sourceFile: ts.SourceFile;
 *   node: ts.Node;
 *   ownerSymbol: string;
 *   containerPath: string[];
 *   parentContainerId: string;
 *   nextOrder: () => number;
 * }} options
 * @returns {(InventoryUnitRecord & { node: ts.Node; sourceFile: ts.SourceFile; }) | undefined}
 */
function createMemberUnit(options) {
    const {
        fileRecord,
        sourceFile,
        node,
        ownerSymbol,
        containerPath,
        parentContainerId,
        nextOrder,
    } = options;

    const memberName = getMemberName(node, sourceFile);

    if (!memberName) {
        return undefined;
    }

    /** @type {InventoryUnitRecord & { node: ts.Node; sourceFile: ts.SourceFile; }} */
    const unit = {
        id: createUnitId(fileRecord.libFileName, `${ownerSymbol}.${memberName}`, nextOrder()),
        libFileName: fileRecord.libFileName,
        unitKind: "member",
        declarationKind: "member",
        containerPath,
        parentContainerId,
        containerId: undefined,
        symbolName: undefined,
        ownerSymbol,
        memberName,
        typeRefName: undefined,
        declaredSymbols: [],
        dependencySymbols: [],
        dependencyUnitIds: [],
        order: fileRecord.unitIds.length,
        text: getNodeText(fileRecord.sourceText, node),
        parameterNames: getParameterNames(node),
        surfacePath: `${ownerSymbol}.${memberName}`,
        node,
        sourceFile,
    };

    fileRecord.unitIds.push(unit.id);

    return unit;
}

/**
 * @param {{
 *   unit: InventoryUnitRecord & { node: ts.Node; sourceFile: ts.SourceFile; };
 *   declarationUnitIdsBySymbol: Map<string, string[]>;
 * }} options
 */
function collectDependencySymbols(options) {
    const {
        unit,
        declarationUnitIdsBySymbol,
    } = options;

    const typeParameterNames = getTypeParameterNames(unit.node);
    const dependencySymbols = new Set();

    /**
     * @param {ts.Node} node
     */
    function visit(node) {
        if (ts.isTypeReferenceNode(node)) {
            addReference(node.typeName.getText(unit.sourceFile));
        }
        else if (ts.isExpressionWithTypeArguments(node)) {
            addReference(node.expression.getText(unit.sourceFile));
        }
        else if (ts.isTypeQueryNode(node)) {
            addReference(node.exprName.getText(unit.sourceFile));
        }
        else if (ts.isHeritageClause(node)) {
            for (const heritageType of node.types) {
                addReference(heritageType.expression.getText(unit.sourceFile));
            }
        }

        ts.forEachChild(node, visit);
    }

    visit(unit.node);

    for (const declaredSymbol of unit.declaredSymbols) {
        dependencySymbols.delete(declaredSymbol);
    }

    for (const typeParameterName of typeParameterNames) {
        dependencySymbols.delete(typeParameterName);

        for (const prefix of unit.containerPath.map((_, index) => unit.containerPath.slice(0, index + 1).join("."))) {
            dependencySymbols.delete(`${prefix}.${typeParameterName}`);
        }
    }

    return [...dependencySymbols]
        .filter(symbol => declarationUnitIdsBySymbol.has(symbol))
        .sort(compareStringsCaseSensitive);

    /**
     * @param {string} referenceText
     */
    function addReference(referenceText) {
        if (!referenceText || referenceText.includes("<") || typeParameterNames.has(referenceText)) {
            return;
        }

        const namespacePath = unit.unitKind === "member" ? unit.containerPath.slice(0, -1) : unit.containerPath;
        const normalized = normalizeReference(referenceText, namespacePath, declarationUnitIdsBySymbol);

        if (normalized) {
            dependencySymbols.add(normalized);
        }
    }
}

/**
 * @param {InventoryUnitRecord & { node: ts.Node; sourceFile: ts.SourceFile; }} unit
 * @param {Map<string, string[]>} declarationUnitIdsBySymbol
 */
function collectHeritageSymbols(unit, declarationUnitIdsBySymbol) {
    if (!ts.isInterfaceDeclaration(unit.node) && !ts.isClassDeclaration(unit.node)) {
        return [];
    }

    const symbols = new Set();

    for (const clause of unit.node.heritageClauses ?? []) {
        if (clause.token !== ts.SyntaxKind.ExtendsKeyword) {
            continue;
        }

        for (const type of clause.types) {
            const symbol = normalizeReference(type.expression.getText(unit.sourceFile), unit.containerPath, declarationUnitIdsBySymbol);

            if (symbol && declarationUnitIdsBySymbol.has(symbol)) {
                symbols.add(symbol);
            }
        }
    }

    return [...symbols].sort(compareStringsCaseSensitive);
}

/**
 * @param {Map<string, RootSurfaceRecord>} rootSurfaceByCompatName
 * @param {InventoryUnitRecord} declarationUnit
 */
function registerRootSurface(rootSurfaceByCompatName, declarationUnit) {
    if (declarationUnit.unitKind !== "declaration" || !declarationUnit.symbolName) {
        return;
    }

    let root = rootSurfaceByCompatName.get(declarationUnit.symbolName);

    if (!root) {
        root = {
            compatName: declarationUnit.symbolName,
            rootDeclarationUnitIds: [],
            instanceContainerSymbols: new Set(),
            staticContainerSymbols: new Set(),
        };
        rootSurfaceByCompatName.set(declarationUnit.symbolName, root);
    }

    switch (declarationUnit.declarationKind) {
        case "var":
            root.rootDeclarationUnitIds.push(declarationUnit.id);

            if (declarationUnit.typeRefName) {
                root.staticContainerSymbols.add(declarationUnit.typeRefName);
            }

            break;
        case "function":
        case "enum":
        case "type-alias":
        case "namespace":
            root.rootDeclarationUnitIds.push(declarationUnit.id);
            root.staticContainerSymbols.add(declarationUnit.symbolName);
            break;
        case "class":
            root.rootDeclarationUnitIds.push(declarationUnit.id);
            root.instanceContainerSymbols.add(declarationUnit.symbolName);
            root.staticContainerSymbols.add(declarationUnit.symbolName);
            break;
        case "interface":
            root.instanceContainerSymbols.add(declarationUnit.symbolName);
            break;
        default:
            break;
    }
}

/**
 * @param {SurfaceInventory} inventory
 * @param {string} libFileName
 * @param {Set<string>} selectedUnitIds
 * @param {Map<string, string>} unitTextOverrides
 * @param {Set<string>} completeContainerUnitIds
 * @param {Set<string>} excludedUnitIds
 * @param {Set<string> | undefined} emittedUnitIds
 * @returns {string | undefined}
 */
function emitFileSelection(inventory, libFileName, selectedUnitIds, unitTextOverrides, completeContainerUnitIds, excludedUnitIds, emittedUnitIds) {
    const fileRecord = inventory.fileByLibFileName.get(libFileName);

    if (!fileRecord) {
        return undefined;
    }

    const fileUnits = inventory.unitsByLibFileName.get(libFileName) ?? [];

    if (!fileUnits.some(unit => selectedUnitIds.has(unit.id))) {
        return undefined;
    }

    if (fileRecord.preserveWholeFile) {
        // Whole-file preservation skips unit-level selection, so passing
        // through a file that contains excluded units would leak non-Baseline
        // surface wholesale. Selection can't fix that state, so fail closed.
        const excludedInFile = fileUnits
            .filter(unit => excludedUnitIds.has(unit.id))
            .map(unit => unit.id)
            .sort(compareStringsCaseSensitive);

        if (excludedInFile.length) {
            throw new Error(
                `Cannot emit whole-file lib ${libFileName}: it contains units excluded from the baseline target:\n${excludedInFile
                    .map(unitId => `- ${unitId}`)
                    .join("\n")}`,
            );
        }

        for (const unit of fileUnits) {
            emittedUnitIds?.add(unit.id);
        }

        return [
            `/////////////////////////////`,
            `// ${libFileName}`,
            `/////////////////////////////`,
            stripSourceFilePreamble(fileRecord.sourceText).trimEnd(),
        ].join("\n");
    }

    const topLevelUnits = fileUnits.filter(unit => !unit.parentContainerId);
    /** @type {string[]} */
    const sections = [];

    for (const unit of topLevelUnits) {
        const emitted = emitUnit(inventory, unit.id, selectedUnitIds, unitTextOverrides, completeContainerUnitIds, excludedUnitIds, emittedUnitIds);

        if (emitted) {
            sections.push(emitted.trimEnd());
        }
    }

    if (!sections.length) {
        return undefined;
    }

    return [
        `/////////////////////////////`,
        `// ${libFileName}`,
        `/////////////////////////////`,
        sections.join("\n\n"),
    ].join("\n");
}

/**
 * @param {SurfaceInventory} inventory
 * @param {string} unitId
 * @param {Set<string>} selectedUnitIds
 * @param {Map<string, string>} unitTextOverrides
 * @param {Set<string>} completeContainerUnitIds
 * @param {Set<string>} excludedUnitIds
 * @param {Set<string> | undefined} emittedUnitIds
 * @param {boolean} [forceEmit]
 * @returns {string | undefined}
 */
function emitUnit(inventory, unitId, selectedUnitIds, unitTextOverrides, completeContainerUnitIds, excludedUnitIds, emittedUnitIds, forceEmit = false) {
    // Never emit an excluded unit, even through complete-container forceEmit.
    // The generator's invariant already rejects any intersection with the
    // selection set, so this acts as a mechanical last-resort guard.
    if (excludedUnitIds.has(unitId)) {
        return undefined;
    }

    const unit = inventory.unitById.get(unitId);

    if (!unit) {
        return undefined;
    }

    const childUnits = unit.containerId ? getChildUnits(inventory, unit.containerId) : [];
    /** @type {string[]} */
    const selectedChildEmissions = [];
    const forceChildren = forceEmit || completeContainerUnitIds.has(unit.id);

    for (const child of childUnits) {
        const childEmission = emitUnit(
            inventory,
            child.id,
            selectedUnitIds,
            unitTextOverrides,
            completeContainerUnitIds,
            excludedUnitIds,
            emittedUnitIds,
            forceChildren,
        );

        if (childEmission) {
            selectedChildEmissions.push(childEmission);
        }
    }

    const isSelected = forceEmit || selectedUnitIds.has(unitId);
    const hasSelectedChildren = selectedChildEmissions.length > 0;

    if (!isSelected && !hasSelectedChildren) {
        return undefined;
    }

    if (unit.unitKind === "declaration" && unit.containerId) {
        const container = inventory.containerById.get(unit.containerId);

        if (!container) {
            throw new Error(`Missing container ${unit.containerId} for unit ${unit.id}`);
        }

        emittedUnitIds?.add(unit.id);

        if (!selectedChildEmissions.length) {
            return `${container.headerText}\n${container.footerText}`.trimEnd();
        }

        return `${container.headerText}\n${selectedChildEmissions.join("\n\n")}\n${container.footerText}`.trimEnd();
    }

    if (unit.unitKind === "declaration" && !unit.containerId) {
        emittedUnitIds?.add(unit.id);

        return stripSourceFilePreamble(unitTextOverrides.get(unit.id) ?? unit.text).trimEnd();
    }

    emittedUnitIds?.add(unit.id);

    return (unitTextOverrides.get(unit.id) ?? unit.text).trimEnd();
}

/**
 * @param {SurfaceInventory} inventory
 * @param {string} containerId
 */
function getChildUnits(inventory, containerId) {
    return inventory.units
        .filter(unit => unit.parentContainerId === containerId)
        .sort(compareUnitsByOrder);
}

