/**
 * @param {ts.Statement} statement
 * @param {string[]} containerPath
 */
function getStatementSymbolName(statement, containerPath) {
    if (
        ts.isInterfaceDeclaration(statement)
        || ts.isTypeAliasDeclaration(statement)
        || ts.isClassDeclaration(statement)
        || ts.isEnumDeclaration(statement)
        || ts.isFunctionDeclaration(statement)
        || ts.isModuleDeclaration(statement)
    ) {
        if (statement.name && ts.isIdentifier(statement.name)) {
            return formatSymbolName(containerPath, statement.name.text);
        }
    }

    if (ts.isVariableStatement(statement)) {
        const declaration = statement.declarationList.declarations[0];

        if (declaration && ts.isIdentifier(declaration.name)) {
            return formatSymbolName(containerPath, declaration.name.text);
        }
    }

    return undefined;
}

/**
 * @param {ts.Statement} statement
 */
function getDeclarationKind(statement) {
    if (ts.isInterfaceDeclaration(statement)) {
        return "interface";
    }

    if (ts.isTypeAliasDeclaration(statement)) {
        return "type-alias";
    }

    if (ts.isClassDeclaration(statement)) {
        return "class";
    }

    if (ts.isEnumDeclaration(statement)) {
        return "enum";
    }

    if (ts.isFunctionDeclaration(statement)) {
        return "function";
    }

    if (ts.isModuleDeclaration(statement)) {
        return "namespace";
    }

    if (ts.isVariableStatement(statement)) {
        return "var";
    }

    return "statement";
}

/**
 * @param {ts.Statement} statement
 */
function getTypeReferenceName(statement) {
    if (!ts.isVariableStatement(statement)) {
        return undefined;
    }

    const declaration = statement.declarationList.declarations[0];

    if (!declaration?.type) {
        return undefined;
    }

    if (ts.isTypeReferenceNode(declaration.type)) {
        return declaration.type.typeName.getText();
    }

    return declaration.type.getText();
}

/**
 * @param {ts.Node} node
 * @param {ts.SourceFile} sourceFile
 */
function getMemberName(node, sourceFile) {
    if (
        ts.isMethodSignature(node)
        || ts.isMethodDeclaration(node)
        || ts.isPropertySignature(node)
        || ts.isPropertyDeclaration(node)
        || ts.isGetAccessorDeclaration(node)
        || ts.isSetAccessorDeclaration(node)
        || ts.isIndexSignatureDeclaration(node)
    ) {
        if (ts.isIndexSignatureDeclaration(node)) {
            return "<index>";
        }

        return getPropertyNameText(node.name, sourceFile);
    }

    if (ts.isConstructSignatureDeclaration(node) || ts.isConstructorDeclaration(node)) {
        return "<construct>";
    }

    if (ts.isCallSignatureDeclaration(node)) {
        return "<call>";
    }

    return undefined;
}

/**
 * @param {ts.PropertyName | undefined} name
 * @param {ts.SourceFile} sourceFile
 */
function getPropertyNameText(name, sourceFile) {
    if (!name) {
        return undefined;
    }

    if (ts.isIdentifier(name) || ts.isPrivateIdentifier(name)) {
        return name.text;
    }

    if (ts.isStringLiteral(name) || ts.isNumericLiteral(name)) {
        return name.text;
    }

    if (ts.isComputedPropertyName(name)) {
        const text = name.expression.getText(sourceFile);

        switch (text) {
            case "Symbol.iterator":
                return "@@iterator";
            case "Symbol.asyncIterator":
                return "@@asyncIterator";
            case "Symbol.species":
                return "@@species";
            case "Symbol.match":
                return "@@match";
            case "Symbol.matchAll":
                return "@@matchAll";
            case "Symbol.replace":
                return "@@replace";
            case "Symbol.search":
                return "@@search";
            case "Symbol.split":
                return "@@split";
            case "Symbol.toPrimitive":
                return "@@toPrimitive";
            case "Symbol.toStringTag":
                return "@@toStringTag";
            case "Symbol.hasInstance":
                return "@@hasInstance";
            case "Symbol.isConcatSpreadable":
                return "@@isConcatSpreadable";
            case "Symbol.unscopables":
                return "@@unscopables";
            case "Symbol.asyncDispose":
                return "@@asyncDispose";
            case "Symbol.dispose":
                return "@@dispose";
            default:
                return text;
        }
    }

    return name.getText(sourceFile);
}

/**
 * @param {ts.Node} node
 */
function getParameterNames(node) {
    if (
        !ts.isFunctionDeclaration(node)
        && !ts.isMethodSignature(node)
        && !ts.isMethodDeclaration(node)
        && !ts.isConstructSignatureDeclaration(node)
        && !ts.isConstructorDeclaration(node)
        && !ts.isCallSignatureDeclaration(node)
        && !ts.isFunctionTypeNode(node)
        && !ts.isArrowFunction(node)
    ) {
        return [];
    }

    /** @type {string[]} */
    const parameterNames = [];

    for (const parameter of node.parameters) {
        if (ts.isIdentifier(parameter.name)) {
            parameterNames.push(parameter.name.text);
        }
    }

    return parameterNames;
}

/**
 * @param {ts.Node} node
 */
function getTypeParameterNames(node) {
    const typeParameterNames = new Set();

    /**
     * @param {readonly ts.TypeParameterDeclaration[] | undefined} typeParameters
     */
    function addTypeParameters(typeParameters) {
        for (const typeParameter of typeParameters ?? []) {
            typeParameterNames.add(typeParameter.name.text);
        }
    }

    if (
        ts.isInterfaceDeclaration(node)
        || ts.isTypeAliasDeclaration(node)
        || ts.isClassDeclaration(node)
        || ts.isFunctionDeclaration(node)
        || ts.isMethodSignature(node)
        || ts.isMethodDeclaration(node)
        || ts.isConstructSignatureDeclaration(node)
        || ts.isCallSignatureDeclaration(node)
    ) {
        addTypeParameters(node.typeParameters);
    }

    return typeParameterNames;
}

/**
 * @param {ts.SourceFile} sourceFile
 */
function getReferenceLibs(sourceFile) {
    return sourceFile.libReferenceDirectives.map(directive => directive.fileName);
}

/**
 * @param {string} sourceText
 */
function stripReferenceDirectives(sourceText) {
    const sourceFile = ts.createSourceFile(
        "lib.d.ts",
        sourceText,
        ts.ScriptTarget.Latest,
        /*setParentNodes*/ false,
        ts.ScriptKind.TS,
    );

    let stripped = sourceText;

    for (const directive of [...sourceFile.libReferenceDirectives].reverse()) {
        const lineStart = stripped.lastIndexOf("\n", directive.pos - 1) + 1;
        const nextLineStart = stripped.indexOf("\n", directive.end);
        const lineEnd = nextLineStart === -1 ? stripped.length : nextLineStart + 1;
        stripped = stripped.slice(0, lineStart) + stripped.slice(lineEnd);
    }

    return stripped.trim();
}

/**
 * @param {string} sourceText
 */
function stripTypeScriptSourceLicenseHeader(sourceText) {
    return sourceText.replace(TYPESCRIPT_SOURCE_LICENSE_HEADER_PATTERN, "");
}

/**
 * @param {string} sourceText
 */
function stripSourceFilePreamble(sourceText) {
    return stripReferenceDirectives(stripTypeScriptSourceLicenseHeader(sourceText));
}

/**
 * @param {ts.SourceFile} sourceFile
 */
function shouldPreserveWholeFile(sourceFile) {
    return ts.isExternalModule(sourceFile)
        || sourceFile.statements.some(statement =>
            ts.isModuleDeclaration(statement) && (statement.flags & ts.NodeFlags.GlobalAugmentation) !== 0,
        );
}

/**
 * Built-in lib files may use an empty export marker to enable `declare global`,
 * but the generated lib must never expose a module API.
 *
 * @param {ts.SourceFile} sourceFile
 * @param {string} libFileName
 */
function assertGlobalLibScope(sourceFile, libFileName) {
    if (sourceFile.referencedFiles.length) {
        throw new Error(`${libFileName} contains a path reference; baseline lib inputs must be self-contained`);
    }

    if (sourceFile.typeReferenceDirectives.length) {
        throw new Error(`${libFileName} contains a types reference; baseline lib inputs must be self-contained`);
    }

    if (sourceFile.amdDependencies.length || sourceFile.moduleName) {
        throw new Error(`${libFileName} contains AMD metadata; baseline lib inputs must be self-contained`);
    }

    /** @param {ts.Node} node */
    function rejectModuleDependencies(node) {
        if (ts.isModuleDeclaration(node) && ts.isStringLiteral(node.name)) {
            throw new Error(`${libFileName} contains an ambient module; baseline lib inputs may only declare globals`);
        }

        if (
            ts.isImportDeclaration(node)
            || ts.isImportEqualsDeclaration(node)
            || ts.isImportTypeNode(node)
        ) {
            throw new Error(`${libFileName} contains a module import; baseline lib inputs must be self-contained`);
        }

        ts.forEachChild(node, rejectModuleDependencies);
    }

    for (const statement of sourceFile.statements) {
        if (
            ts.isExportDeclaration(statement)
            && !statement.moduleSpecifier
            && statement.exportClause
            && ts.isNamedExports(statement.exportClause)
            && statement.exportClause.elements.length === 0
        ) {
            continue;
        }

        if (
            ts.isExportDeclaration(statement)
            || ts.isExportAssignment(statement)
            || ts.isNamespaceExportDeclaration(statement)
            || (ts.canHaveModifiers(statement)
                && ts.getModifiers(statement)?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword))
        ) {
            throw new Error(`${libFileName} exposes a module export; baseline lib inputs may only use an empty export marker`);
        }
    }

    rejectModuleDependencies(sourceFile);
}

/**
 * @param {SurfaceInventory} inventory
 * @param {InventoryUnitRecord[]} units
 * @param {{ prefer: "base" | "augment"; }} options
 */
function selectPreferredUnits(inventory, units, options) {
    if (!units.length) {
        return [];
    }

    let candidates = units;
    const stableCandidates = candidates.filter(unit => !isEsNextLibFileName(unit.libFileName));

    if (stableCandidates.length) {
        candidates = stableCandidates;
    }

    const nonScopeSensitiveCandidates = candidates.filter(
        unit => !inventory.fileByLibFileName.get(unit.libFileName)?.preserveWholeFile,
    );

    if (nonScopeSensitiveCandidates.length) {
        candidates = nonScopeSensitiveCandidates;
    }

    const stageRanks = candidates.map(
        unit => inventory.fileByLibFileName.get(unit.libFileName)?.stageRank ?? Number.POSITIVE_INFINITY,
    );

    const preferredStageRank = options.prefer === "base"
        ? Math.min(...stageRanks)
        : Math.max(...stageRanks);

    return candidates
        .filter(
            unit => (inventory.fileByLibFileName.get(unit.libFileName)?.stageRank ?? Number.POSITIVE_INFINITY) === preferredStageRank,
        )
        .sort((left, right) =>
            compareStringsCaseSensitive(left.libFileName, right.libFileName)
            || left.order - right.order
            || compareStringsCaseSensitive(left.id, right.id)
        );
}

/**
 * @param {string} libFileName
 */
function isEsNextLibFileName(libFileName) {
    return /^lib\.esnext(?:\.|\.d\.ts$)/u.test(libFileName);
}

/**
 * @param {string} sourceText
 * @param {ts.Node} node
 */
function getNodeText(sourceText, node) {
    return stripTypeScriptSourceLicenseHeader(getNodeSlice(sourceText, node.getFullStart(), node.end))
        .replace(/^(?:\r?\n)+/, "")
        .trimEnd();
}

/**
 * @param {string} sourceText
 * @param {number} start
 * @param {number} end
 */
function getNodeSlice(sourceText, start, end) {
    return sourceText.slice(start, end);
}

/**
 * @param {string} referenceText
 * @param {string[]} containerPath
 * @param {Map<string, string[]>} declarationUnitIdsBySymbol
 */
function normalizeReference(referenceText, containerPath, declarationUnitIdsBySymbol) {
    if (referenceText.startsWith("globalThis.")) {
        const globalName = referenceText.slice("globalThis.".length);

        return declarationUnitIdsBySymbol.has(globalName) ? globalName : undefined;
    }

    if (referenceText.includes("<")) {
        return undefined;
    }

    for (let index = containerPath.length; index >= 1; index--) {
        const candidate = formatSymbolName(containerPath.slice(0, index), referenceText);

        if (declarationUnitIdsBySymbol.has(candidate)) {
            return candidate;
        }
    }

    return referenceText;
}

/**
 * @param {string[]} containerPath
 * @param {string} symbolName
 */
function formatSymbolName(containerPath, symbolName) {
    const symbolPath = containerPath[0] === "global" ? containerPath.slice(1) : containerPath;

    return symbolPath.length ? `${symbolPath.join(".")}.${symbolName}` : symbolName;
}

/**
 * @param {string} libFileName
 * @param {string} key
 * @param {number} order
 */
function createUnitId(libFileName, key, order) {
    return `${libFileName}::${key}::${order}`;
}

/**
 * @param {string} ownerSymbol
 * @param {string} memberName
 */
function getMemberLookupKey(ownerSymbol, memberName) {
    return `${ownerSymbol}::${memberName}`;
}

/**
 * @param {InventoryUnitRecord} left
 * @param {InventoryUnitRecord} right
 */
function compareUnitsByOrder(left, right) {
    return left.order - right.order || compareStringsCaseSensitive(left.id, right.id);
}

